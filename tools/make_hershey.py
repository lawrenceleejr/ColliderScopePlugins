#!/usr/bin/env python3
"""Turns the Hershey .jhf fonts into core/src/hershey_data.inc.

usage: tools/make_hershey.py core/third_party/hershey core/src/hershey_data.inc

Each font becomes an array of 96 C strings, one per glyph, for the
characters 32 to 127: the .jhf line from its 9th column on (left and right
bounds, then coordinate pairs; " R" lifts the pen).
"""
import sys

def glyphs(path):
    lines = [l for l in open(path, encoding="latin-1").read().split("\n") if len(l) >= 10]
    out = [l[8:] for l in lines[:96]]
    return out + ["RR"] * (96 - len(out))

def literal(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

src, dst = sys.argv[1], sys.argv[2]
with open(dst, "w") as f:
    f.write("// Generated by tools/make_hershey.py from core/third_party/hershey. Do not edit.\n")
    f.write("// Hershey fonts: see core/third_party/hershey/README.md for the acknowledgement.\n")
    for name, file in (("kRoman", "futural.jhf"), ("kGreek", "greek.jhf"), ("kMath", "mathlow.jhf")):
        f.write(f"static const char* const {name}[96] = {{\n")
        for g in glyphs(f"{src}/{file}"):
            f.write(f"    {literal(g)},\n")
        f.write("};\n")
